// CivicConnect small load test (M3 performance evidence, NFR-001).
//
// Workload: N virtual requesters, each repeatedly (1) submits a request and (2) reloads "My requests",
// with no think time, for a fixed duration. Submission is the main write path (SQLite allows one writer
// at a time, ADR-07) and the list is the most frequent read, so this is the most performance-sensitive
// requester journey.
//
// Usage:  dotnet run --project tools/CivicConnect.LoadTest -c Release -- <baseUrl> <users> <seconds>
// The demo password is read from the CIVICCONNECT_STAGING_PASSWORD environment variable.

using System.Diagnostics;
using System.Globalization;
using System.Net;
using System.Net.Http.Json;

var baseUrl = new Uri(args.ElementAtOrDefault(0) ?? "http://localhost:5090");
var users = int.Parse(args.ElementAtOrDefault(1) ?? "10", CultureInfo.InvariantCulture);
var duration = TimeSpan.FromSeconds(int.Parse(args.ElementAtOrDefault(2) ?? "60", CultureInfo.InvariantCulture));
var password = Environment.GetEnvironmentVariable("CIVICCONNECT_STAGING_PASSWORD")
               ?? throw new InvalidOperationException("Set CIVICCONNECT_STAGING_PASSWORD.");

var samples = new System.Collections.Concurrent.ConcurrentBag<Sample>();

// Each virtual user gets its own cookie jar and logs in once (alternating the two demo requesters).
var clients = new List<HttpClient>();
for (var i = 0; i < users; i++)
{
    var client = new HttpClient(new HttpClientHandler { CookieContainer = new CookieContainer() }) { BaseAddress = baseUrl };
    var login = await client.PostAsJsonAsync("/api/auth/login",
        new { userId = i % 2 == 0 ? "requester-1" : "requester-2", password });
    login.EnsureSuccessStatusCode();
    clients.Add(client);
}

Console.WriteLine($"Target {baseUrl}  |  {users} concurrent users  |  {duration.TotalSeconds:0} s");
var stopAt = DateTime.UtcNow + duration;
var total = Stopwatch.StartNew();

await Task.WhenAll(clients.Select(async (client, user) =>
{
    var n = 0;
    while (DateTime.UtcNow < stopAt)
    {
        n++;
        await Measure("submit", () => client.PostAsJsonAsync("/api/requests",
            new { category = "Roads", title = $"Load test u{user} #{n}", description = "Generated by the M3 load test" }));
        await Measure("list", () => client.GetAsync("/api/requests"));
    }
}));
total.Stop();

// ---- Report -------------------------------------------------------------------------------------------
Console.WriteLine();
Console.WriteLine("| Operation | Requests | Errors | Error rate | p50 ms | p95 ms | Max ms | Throughput req/s |");
Console.WriteLine("|---|---|---|---|---|---|---|---|");
foreach (var group in samples.GroupBy(s => s.Operation).OrderBy(g => g.Key))
{
    var times = group.Select(s => s.Milliseconds).OrderBy(t => t).ToArray();
    var errors = group.Count(s => !s.Succeeded);
    Console.WriteLine($"| {group.Key} | {times.Length} | {errors} | {(double)errors / times.Length:P1} | " +
                      $"{Percentile(times, 50):0} | {Percentile(times, 95):0} | {times[^1]:0} | " +
                      $"{times.Length / total.Elapsed.TotalSeconds:0.0} |");
}
foreach (var failure in samples.Where(s => !s.Succeeded).GroupBy(s => $"{s.Operation} -> {s.Status}"))
    Console.WriteLine($"Failure: {failure.Key} x{failure.Count()}");

return samples.Any(s => !s.Succeeded) ? 1 : 0;

async Task Measure(string operation, Func<Task<HttpResponseMessage>> call)
{
    var timer = Stopwatch.StartNew();
    try
    {
        using var response = await call();
        samples.Add(new Sample(operation, timer.Elapsed.TotalMilliseconds, response.IsSuccessStatusCode, ((int)response.StatusCode).ToString(CultureInfo.InvariantCulture)));
    }
    catch (HttpRequestException ex)
    {
        samples.Add(new Sample(operation, timer.Elapsed.TotalMilliseconds, false, ex.GetType().Name));
    }
}

static double Percentile(double[] sorted, int percentile) =>
    sorted[Math.Clamp((int)Math.Ceiling(percentile / 100.0 * sorted.Length) - 1, 0, sorted.Length - 1)];

sealed record Sample(string Operation, double Milliseconds, bool Succeeded, string Status);
